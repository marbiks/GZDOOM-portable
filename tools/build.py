#!/usr/bin/env python3
"""Build the two player folders under builds/.

  builds/normal/   the launcher and all three engines, as shipped
  builds/lite/     the same without the optional widescreen artwork package

Both folders are self-contained: index.html at the top, the engines under
engine/, the licence files beside them. They are generated output, not tracked
(builds/ is in .gitignore), so the repository keeps one copy of the payloads.

The lite build drops `game_widescreen_gfx.pk3` from all three containers; GZDoom
then draws the classic 4:3 status bars and menus, exactly as it does upstream
when the pack is missing. Saves, settings, engines and mod support are
untouched.

    python3 tools/build.py            # both builds
    python3 tools/build.py --normal   # one of them
    python3 tools/build.py --lite
    python3 tools/build.py --check    # report sizes, write nothing
"""
import base64
import json
import os
import re
import shutil
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BUILDS = os.path.join(ROOT, 'builds')
DROP = 'game_widescreen_gfx.pk3'
MB = 1048576.0

# Everything a player needs; documentation that is not shipped stays in docs/.
COPY = [
    'index.html', 'launcher.js', 'engines.js',
    'README.md', 'LICENSE', 'PROVENANCE.md',
    'licenses/GPL-3.0.txt', 'licenses/README.txt',
    'saves/README.txt', 'config/README.txt', 'backups/README.txt',
    'engine/gzdoom/portable-engine.js',
    'engine/gzdoom/portable-data.js',
    'engine/gzdoom414/glue.js',
    'engine/gzdoom414/driver.js',
    'engine/gzdoom414/wasm-b64.js',
    'engine/gzdoom414/data-b64.js',
    'engine/uzdoom/bundle.js',
]

PK3S_LINE = ("const PK3S = ['gzdoom.pk3', 'brightmaps.pk3', 'game_support.pk3', "
             "'game_widescreen_gfx.pk3', 'lights.pk3'];")


def src(rel):
    return os.path.join(ROOT, rel)


def dst(out, rel):
    return os.path.join(out, rel)


def read(path, binary=False):
    mode = 'rb' if binary else 'r'
    kw = {} if binary else {'encoding': 'utf-8'}
    with open(path, mode, **kw) as f:
        return f.read()


def write(out, rel, data, binary=False):
    path = dst(out, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    mode = 'wb' if binary else 'w'
    kw = {} if binary else {'encoding': 'utf-8'}
    with open(path, mode, **kw) as f:
        f.write(data)


def json_body(text):
    return json.loads(text[text.index('{'):text.rindex('}') + 1])


def reset(out):
    if os.path.isdir(out):
        shutil.rmtree(out)
    os.makedirs(out)


def copy_player_files(out):
    for rel in COPY:
        write(out, rel, read(src(rel), binary=True), binary=True)


# --------------------------------------------------------------------- 4.11.3
def lite_4113(out):
    rel = 'engine/gzdoom/portable-data.js'
    data = json_body(read(dst(out, rel)))
    if DROP not in data:
        sys.exit(rel + ' has no ' + DROP)
    del data[DROP]
    write(out, rel, '/* generated by tools/build.py - do not edit */\n'
          'window.GZP_DATA = ' + json.dumps(data, separators=(',', ':')) + ';\n')

    # The worker copies exactly this list into MEMFS, so the name goes too.
    launcher = read(dst(out, 'launcher.js'))
    if PK3S_LINE not in launcher:
        sys.exit('launcher.js PK3S line changed; update tools/build.py')
    launcher = launcher.replace(
        PK3S_LINE,
        "const PK3S = ['gzdoom.pk3', 'brightmaps.pk3', 'game_support.pk3', 'lights.pk3'];")
    write(out, 'launcher.js', launcher)


# --------------------------------------------------------------------- 4.14.2
def lite_4142(out):
    rel = 'engine/gzdoom414/data-b64.js'
    text = read(dst(out, rel))
    header = text[:text.index('*/') + 2] + '\n'
    blob = base64.b64decode(json.loads('"' + text.split('"', 1)[1].rsplit('"', 1)[0] + '"'))

    glue_rel = 'engine/gzdoom414/glue.js'
    glue = read(dst(out, glue_rel))
    match = None
    for cand in re.finditer(r'loadPackage\((\{.*?\})\);', glue, 0):
        if 'remote_package_size' in cand.group(1):
            match = cand
            break
    if not match:
        sys.exit('glue.js loadPackage metadata not found')
    meta = json.loads(match.group(1))
    files = [f for f in meta['files'] if os.path.basename(f['filename']) != DROP]
    if len(files) == len(meta['files']):
        sys.exit('glue.js metadata has no ' + DROP)

    # Re-cut the blob in the metadata's own order, skipping the dropped slice.
    pieces, offset, newfiles = [], 0, []
    for f in files:
        pieces.append(blob[f['start']:f['end']])
        newfiles.append({'filename': f['filename'], 'start': offset,
                         'end': offset + (f['end'] - f['start'])})
        offset += f['end'] - f['start']
    newblob = b''.join(pieces)
    meta = {'files': newfiles, 'remote_package_size': len(newblob)}

    glue = glue[:match.start(1)] + json.dumps(meta, separators=(',', ':')) + glue[match.end(1):]
    write(out, glue_rel, glue)
    write(out, rel, header + 'window.GZ414_DATA_B64 = "'
          + base64.b64encode(newblob).decode('ascii') + '";\n')
    print('  4.14.2 data blob %.1f MB -> %.1f MB' % (len(blob) / MB, len(newblob) / MB))


# --------------------------------------------------------------------- UZDoom
def lite_uzdoom(out):
    rel = 'engine/uzdoom/bundle.js'
    text = read(dst(out, rel))
    head = text[:text.index('window.GZ_ENGINE_BUNDLE')]
    payload = json_body(text)
    if DROP not in payload.get('archives', {}):
        sys.exit(rel + ' has no ' + DROP)
    del payload['archives'][DROP]
    write(out, rel, head + 'window.GZ_ENGINE_BUNDLE = ' + json.dumps(payload) + ';\n')


def report(name, out):
    total, files = 0, 0
    for base, _dirs, names in os.walk(out):
        for n in names:
            total += os.path.getsize(os.path.join(base, n))
            files += 1
    print('builds/%-6s %5.1f MB in %d files' % (name, total / MB, files))


def main():
    check = '--check' in sys.argv
    want_normal = '--lite' not in sys.argv or '--normal' in sys.argv
    want_lite = '--normal' not in sys.argv or '--lite' in sys.argv
    if check:
        total = sum(os.path.getsize(src(p)) for p in COPY)
        print('would write builds/normal and builds/lite from %d files (%.1f MB)'
              % (len(COPY), total / MB))
        return

    if want_normal:
        out = os.path.join(BUILDS, 'normal')
        reset(out)
        copy_player_files(out)
        report('normal', out)

    if want_lite:
        out = os.path.join(BUILDS, 'lite')
        reset(out)
        copy_player_files(out)
        lite_4113(out)
        lite_4142(out)
        lite_uzdoom(out)
        report('lite', out)


if __name__ == '__main__':
    main()

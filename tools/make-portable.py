#!/usr/bin/env python3
"""Build the self-contained GZDoom bundles used by the portable launcher.

The launcher must run from file:// where fetch()/XHR and file:// workers are
blocked. Everything the engine needs at runtime therefore has to arrive as a
classic <script> (allowed on file://) and be turned into a Blob worker.

Outputs (all under engine/gzdoom/):
  portable-engine.js   worker source + Emscripten loader source + wasm
  portable-data.js     support PK3s (base64)

The raw build inputs (gzdoom.js, gzdoom.wasm and the support PK3s) are not kept
next to the generated bundles - each of them is already inside one. They are
recreated on demand from those bundles, so this script still works on a trimmed
folder:

Usage: python3 tools/make-portable.py [--from-bundle]

  --from-bundle  rewrite every input from the bundles (default: only the
                 missing ones), which is also how a checksum can be checked
                 against the shipped payloads.

No game data is part of this project: the launcher asks for an IWAD at run time.
"""
import base64
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ENGINE = os.path.join(ROOT, "engine")
OUT = os.path.join(ENGINE, "gzdoom")

SUPPORT_PK3S = ("gzdoom.pk3", "brightmaps.pk3", "game_support.pk3",
                "game_widescreen_gfx.pk3", "lights.pk3")


def b64file(path):
    with open(path, "rb") as f:
        return base64.b64encode(f.read()).decode("ascii")


def textfile(path):
    with open(path, "r", encoding="utf-8") as f:
        return f.read()


def load_bundle(name):
    path = os.path.join(OUT, name)
    text = open(path, "r", encoding="utf-8").read()
    return json.loads(text[text.index("{"):text.rindex("}") + 1])


def restore_inputs(force=False):
    """Recreate the build inputs the bundles were generated from."""
    engine = load_bundle("portable-engine.js")
    data = load_bundle("portable-data.js")
    files = {
        "gzdoom.js": engine["loader"].encode("utf-8"),
        "gzdoom.wasm": base64.b64decode(engine["wasm"]),
    }
    for name, b64 in data.items():
        files[name] = base64.b64decode(b64)
    for name, blob in files.items():
        dest = os.path.join(OUT, name)
        if force or not os.path.exists(dest):
            with open(dest, "wb") as f:
                f.write(blob)
            print("restored %-28s %8.1f MB" % (name, len(blob) / 1048576.0))


def write_js(name, var, obj):
    path = os.path.join(OUT, name)
    with open(path, "w", encoding="utf-8") as f:
        f.write("/* generated by tools/make-portable.py - do not edit */\n")
        f.write("window." + var + " = ")
        json.dump(obj, f, separators=(",", ":"))
        f.write(";\n")
    print("%-28s %8.1f MB" % (name, os.path.getsize(path) / 1048576.0))


def main():
    os.makedirs(OUT, exist_ok=True)
    restore_inputs(force="--from-bundle" in sys.argv)
    engine = {
        "worker": textfile(os.path.join(ENGINE, "engine.worker.js")),
        "loader": textfile(os.path.join(OUT, "gzdoom.js")),
        "wasm": b64file(os.path.join(OUT, "gzdoom.wasm")),
    }
    write_js("portable-engine.js", "GZP_ENGINE", engine)

    data = {}
    for pk3 in SUPPORT_PK3S:
        data[pk3] = b64file(os.path.join(OUT, pk3))
    write_js("portable-data.js", "GZP_DATA", data)


if __name__ == "__main__":
    main()

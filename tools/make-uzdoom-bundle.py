#!/usr/bin/env python3
"""Pack the UZDoom WebAssembly build into engine/uzdoom/bundle.js.

Why a bundle: a page opened from file:// may not fetch() its own files and may
not start a worker from a file:// URL. Classic <script> tags do work, so the
engine glue, the wasm binary and its archives travel as one JavaScript file;
the launcher turns them into a Blob worker (which file:// allows).

Inputs (engine/uzdoom-src/):
    uzdoom.js, uzdoom.wasm, uzdoom.pk3, game_support.pk3, brightmaps.pk3,
    lights.pk3, game_widescreen_gfx.pk3
Output:
    engine/uzdoom/bundle.js  -> window.GZ_ENGINE_BUNDLE

The wasm and the archives are gzipped before base64: a 8.8 MB wasm becomes a
~3.5 MB string instead of 11.7 MB, and the page gunzips it with the browser's
own DecompressionStream while the boot overlay is up.

    python3 tools/make-uzdoom-bundle.py           # from engine/uzdoom-src/
    python3 tools/make-uzdoom-bundle.py --fetch   # download the inputs first

The inputs are not kept in the folder (the bundle already carries them);
--fetch pulls them from the live build this bundle was made from. Nothing in
the launcher or the engines ever touches the network.
"""
import base64
import gzip
import io
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'engine', 'uzdoom-src')
OUT = os.path.join(ROOT, 'engine', 'uzdoom')
WORKER = os.path.join(ROOT, 'engine', 'engine.worker.js')

ARCHIVES = [
    'uzdoom.pk3',
    'game_support.pk3',
    'brightmaps.pk3',
    'game_widescreen_gfx.pk3',
    'lights.pk3',
]


def gz_b64(path):
    raw = open(path, 'rb').read()
    buf = io.BytesIO()
    with gzip.GzipFile(fileobj=buf, mode='wb', compresslevel=9) as f:
        f.write(raw)
    packed = buf.getvalue()
    return base64.b64encode(packed).decode('ascii'), len(raw), len(packed)


REMOTE = 'https://rejectedcoins.com/uzdoom-smoke/'
# `--from-bundle` re-creates the inputs from an existing engine/uzdoom/bundle.js
# instead of the network (the bundle carries the exact glue, wasm and archives).


def fetch_inputs(names):
    import urllib.request
    os.makedirs(SRC, exist_ok=True)
    for name in names:
        dest = os.path.join(SRC, name)
        if os.path.exists(dest):
            continue
        print('fetching %s%s' % (REMOTE, name))
        req = urllib.request.Request(REMOTE + name, headers={'User-Agent': 'Mozilla/5.0 (bundle-builder)'})
        with urllib.request.urlopen(req, timeout=120) as r, open(dest, 'wb') as f:
            f.write(r.read())


def unpack_bundle(path, names):
    os.makedirs(SRC, exist_ok=True)
    text = open(path, encoding='utf-8').read()
    payload = json.loads(text[text.index('{'):text.rstrip().rstrip(';').rindex('}') + 1])
    blob = {'uzdoom.js': payload['loader']}
    blob['uzdoom.wasm'] = base64.b64decode(payload['wasm'])
    for name in ARCHIVES:
        blob[name] = base64.b64decode(payload['archives'][name])
    for name in names:
        data = blob[name]
        if name != 'uzdoom.js' and payload.get('gzip'):
            data = gzip.decompress(data)
        if isinstance(data, str):
            data = data.encode('utf-8')
        open(os.path.join(SRC, name), 'wb').write(data)
        print('unpacked ' + name)


def main():
    names = ['uzdoom.js', 'uzdoom.wasm', *ARCHIVES]
    if '--fetch' in sys.argv:
        fetch_inputs(names)
    if '--from-bundle' in sys.argv:
        unpack_bundle(os.path.join(OUT, 'bundle.js'), names)
    for name in ['uzdoom.js', 'uzdoom.wasm', 'engine.worker.js', *ARCHIVES]:
        path = WORKER if name == 'engine.worker.js' else os.path.join(SRC, name)
        if not os.path.exists(path):
            sys.exit('missing %s (run with --fetch to download the build inputs)' % path)

    glue = open(os.path.join(SRC, 'uzdoom.js'), encoding='utf-8').read()
    worker = open(WORKER, encoding='utf-8').read()

    wasm_b64, wasm_raw, wasm_packed = gz_b64(os.path.join(SRC, 'uzdoom.wasm'))
    archives = {}
    total_packed = 0
    for name in ARCHIVES:
        b64, raw, packed = gz_b64(os.path.join(SRC, name))
        archives[name] = b64
        total_packed += packed
        print('%-26s %8.1f KB -> %7.1f KB' % (name, raw / 1024, packed / 1024))

    payload = {
        'id': 'uzdoom',
        'version': 'UZDoom g4.14.3',
        'loader': glue,
        'worker': worker,
        'gzip': True,
        'wasm': wasm_b64,
        'archives': archives,
    }
    js = (
        '/* Generated by tools/make-uzdoom-bundle.py - do not edit.\n'
        ' * UZDoom g4.14.3 wasm build (derpyder/uzdoom-wasm) packed for file://.\n'
        ' * glue + worker source, wasm and engine archives, gzip + base64. */\n'
        'window.GZ_ENGINE_BUNDLE = ' + json.dumps(payload) + ';\n'
    )
    os.makedirs(OUT, exist_ok=True)
    dest = os.path.join(OUT, 'bundle.js')
    with open(dest, 'w', encoding='utf-8') as f:
        f.write(js)
    print('engine/uzdoom/bundle.js  %.1f MB (glue %.1f KB, worker %.1f KB, wasm %.1f KB raw)'
          % (len(js) / 1048576, len(glue) / 1024, len(worker) / 1024, wasm_raw / 1024))


if __name__ == '__main__':
    main()

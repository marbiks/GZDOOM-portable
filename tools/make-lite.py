#!/usr/bin/env python3
"""Build the "lite" folder: the same three engines, without the optional
widescreen artwork pack (`game_widescreen_gfx.pk3`).

Why this file: every engine ships that pack for widescreen status bars and
menus. It is the single largest optional asset in the download (~5.3 MB in each
engine, ~16 MB in the ZIP) and it changes nothing about the game itself - with
it gone GZDoom draws the classic 4:3 status bar artwork, exactly as it does
when the pack is missing upstream.

The pack lives in three different containers, so each one is edited where the
launcher already reads it:

  GZDoom 4.11.3  engine/portable-data.js   - one base64 field per PK3
  GZDoom 4.14.2  engine/gzdoom414/         - one packed blob + the offsets in
                                              glue.js's loadPackage() metadata
  UZDoom         engine/uzdoom/bundle.js   - one gzip+base64 archive per name

`launcher.js` also loses the name from PK3S for the 4.11.3 path, because that
list is what the worker copies into MEMFS.

    python3 tools/make-lite.py          # writes build/lite/
    python3 tools/make-lite.py --check  # report sizes only, write nothing

Nothing here touches the normal build: engine/ in the repo stays as it is.
"""
import base64
import json
import os
import shutil
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'build', 'lite')
DROP = 'game_widescreen_gfx.pk3'
MB = 1048576.0

COPY = [
    'index.html', 'engines.js', 'README.md', 'LICENSE', 'PROVENANCE.md',
    'licenses/GPL-3.0.txt', 'licenses/README.txt',
    'saves/README.txt', 'config/README.txt', 'backups/README.txt',
    'engine/portable-engine.js',
    'engine/gzdoom414/wasm-b64.js',
    'engine/gzdoom414/driver.js',
]

sizes = {}


def read(rel):
    return open(os.path.join(ROOT, rel), encoding='utf-8').read()


def write(rel, text):
    path = os.path.join(OUT, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', encoding='utf-8') as f:
        f.write(text)
    sizes[rel] = os.path.getsize(path)


def json_body(text):
    return json.loads(text[text.index('{'):text.rindex('}') + 1])


def dump_var(rel, var, obj, header=''):
    write(rel, header + 'window.' + var + ' = ' +
          json.dumps(obj, separators=(',', ':')) + ';\n')


# --------------------------------------------------------------------- 4.11.3
def build_4113():
    data = json_body(read('engine/portable-data.js'))
    if DROP not in data:
        sys.exit('portable-data.js has no ' + DROP)
    del data[DROP]
    dump_var('engine/portable-data.js', 'GZP_DATA', data,
             '/* generated by tools/make-lite.py - do not edit */\n')

    # The worker copies exactly this list into MEMFS, so the name goes too.
    launcher = read('launcher.js')
    line = "const PK3S = ['gzdoom.pk3', 'brightmaps.pk3', 'game_support.pk3', 'game_widescreen_gfx.pk3', 'lights.pk3'];"
    if line not in launcher:
        sys.exit('launcher.js PK3S line changed; update tools/make-lite.py')
    launcher = launcher.replace(
        line,
        "const PK3S = ['gzdoom.pk3', 'brightmaps.pk3', 'game_support.pk3', 'lights.pk3'];")
    write('launcher.js', launcher)


# --------------------------------------------------------------------- 4.14.2
def build_4142():
    text = read('engine/gzdoom414/data-b64.js')
    header = text[:text.index('*/') + 2] + '\n'
    blob = base64.b64decode(json.loads('"' + text.split('"', 1)[1].rsplit('"', 1)[0] + '"'))

    glue = read('engine/gzdoom414/glue.js')
    m = None
    for cand in __import__('re').finditer(r'loadPackage\((\{.*?\})\);', glue, 0):
        if 'remote_package_size' in cand.group(1):
            m = cand
            break
    if not m:
        sys.exit('glue.js loadPackage metadata not found')
    meta = json.loads(m.group(1))
    files = [f for f in meta['files'] if os.path.basename(f['filename']) != DROP]
    if len(files) == len(meta['files']):
        sys.exit('glue.js metadata has no ' + DROP)

    # Re-cut the blob in the metadata's own order, skipping the dropped slice.
    pieces, off = [], 0
    newfiles = []
    for f in files:
        pieces.append(blob[f['start']:f['end']])
        newfiles.append({'filename': f['filename'], 'start': off,
                         'end': off + (f['end'] - f['start'])})
        off += f['end'] - f['start']
    newblob = b''.join(pieces)
    meta = {'files': newfiles, 'remote_package_size': len(newblob)}

    glue = glue[:m.start(1)] + json.dumps(meta, separators=(',', ':')) + glue[m.end(1):]
    write('engine/gzdoom414/glue.js', glue)

    write('engine/gzdoom414/data-b64.js',
          header + 'window.GZ414_DATA_B64 = "' + base64.b64encode(newblob).decode('ascii') + '";\n')
    print('  4.14.2 data blob %.1f MB -> %.1f MB' % (len(blob) / MB, len(newblob) / MB))


# --------------------------------------------------------------------- UZDoom
def build_uzdoom():
    text = read('engine/uzdoom/bundle.js')
    head = text[:text.index('window.GZ_ENGINE_BUNDLE')]
    payload = json_body(text)
    if DROP not in payload.get('archives', {}):
        sys.exit('uzdoom bundle has no ' + DROP)
    del payload['archives'][DROP]
    write('engine/uzdoom/bundle.js',
          head + 'window.GZ_ENGINE_BUNDLE = ' + json.dumps(payload) + ';\n')


def main():
    check = '--check' in sys.argv
    if check:
        total = sum(os.path.getsize(os.path.join(ROOT, p)) for p in COPY)
        print('would write build/lite/ from %d copied files (%.1f MB)' % (len(COPY), total / MB))
        return
    if os.path.isdir(OUT):
        shutil.rmtree(OUT)
    for rel in COPY:
        dest = os.path.join(OUT, rel)
        os.makedirs(os.path.dirname(dest), exist_ok=True)
        shutil.copyfile(os.path.join(ROOT, rel), dest)
        sizes[rel] = os.path.getsize(dest)
    for fn in (build_4113, build_4142, build_uzdoom):
        print(fn.__name__)
        fn()
    total = sum(sizes.values())
    print('\nbuild/lite  %.1f MB in %d files' % (total / MB, len(sizes)))
    for rel in sorted(sizes, key=lambda r: -sizes[r])[:6]:
        print('  %-34s %6.2f MB' % (rel, sizes[rel] / MB))


if __name__ == '__main__':
    main()
